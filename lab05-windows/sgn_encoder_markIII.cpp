void encoder(unsigned char code[], size_t size)
{
    std::random_device rd;
    std::mt19937 gen(rd());
    std::uniform_int_distribution<size_t> dist(0, 255);
    uint8_t selected_key = dist(gen);
    unsigned char key = selected_key;


    unsigned char* encoded_bytes = new unsigned char[size];
    size_t start_index = 7;

    bool null_found = false;

    for(size_t i = 0; i<size; i++)
    {   
        size_t current_index = (start_index + i) % size;
        unsigned char byte_val = code[current_index];
        unsigned char encoded_byte = byte_val ^ key;
        encoded_bytes[current_index] = encoded_byte;
        if (encoded_byte == 0x00) 
        {
            null_found = true; 
        }
        key = (key + byte_val) & 0xFF; 
    }
    
    if (null_found)
    {
        std::cout << "[!] key 0x" << std::hex << std::uppercase << (int)selected_key << " icinde null byte uretti! yeniden deneniyor...\n";
        delete[] encoded_bytes; 
        encoder(code, size);    
        return;                 
    }
    
    std::cout << "[+] BASARILI ANAHTAR SECILDI: 0x" << std::hex << std::uppercase << static_cast<int>(selected_key) << "\n";

    char* encoded_str = new char[size * 5 + 1];
    int offset = 0;
    for (size_t i = 0; i < size; i++) 
    {
        offset += sprintf(encoded_str + offset, "0x%02X,", (unsigned int)encoded_bytes[i]);
    }
    if(offset > 0) {
        encoded_str[offset-1] = '\0';
    }
    
    printf("toplam byte sayisi: %zu", size);
    printf("\n[+] Encoded Shellcode:\n");
    printf("%s\n", encoded_str);

    delete[] encoded_bytes;
    delete[] encoded_str;
}

